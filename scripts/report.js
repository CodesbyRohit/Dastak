#!/usr/bin/env node
// Runs the test suites and records their actual output in docs/TEST-RESULTS.md and
// public/test-results.json (shown on the showcase). Nothing here is typed by hand: every
// number comes from a runner's output. If a suite fails, the failure is recorded.
//
// Usage: npm run report               (verify + unit + local browser tests)
//        BASE_URL=https://… npm run report   (also runs the browser/HTTP suite against BASE_URL)
'use strict';

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const run = (cmd, args, env) => spawnSync(cmd, args, {
  cwd: ROOT, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 * 1024 * 1024,
  env: Object.assign({}, process.env, env || {})
});
const num = (re, s) => { const m = re.exec(s); return m ? Number(m[1]) : 0; };

const suites = [];

const verify = run('node', ['verify.js']);
suites.push({ name: 'Protocol validation (npm run verify)', command: 'npm run verify', total: 1, passed: verify.status === 0 ? 1 : 0, failed: verify.status === 0 ? 0 : 1 });

const unit = run('npm', ['test', '--silent'], { AI_API_KEY: '', AI_API_URL: '' });
const unitOut = unit.stdout + unit.stderr;
const uTotal = num(/ℹ tests (\d+)/, unitOut);
const uFail = num(/ℹ fail (\d+)/, unitOut);
suites.push({ name: 'Unit tests (npm test)', command: 'npm test', total: uTotal, passed: uTotal - uFail, failed: uFail || (unit.status === 0 ? 0 : 1) });
const covMatch = /all files\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)/.exec(unitOut);
const coverage = covMatch ? { line: Number(covMatch[1]), branch: Number(covMatch[2]), funcs: Number(covMatch[3]) } : null;

function playwright(project, env) {
  const r = run('npx', ['playwright', 'test', '--project=' + project, '--reporter=json'], env);
  let stats = null;
  try { stats = JSON.parse(r.stdout).stats; } catch (e) { /* runner failed before reporting */ }
  if (!stats) return { total: 0, passed: 0, failed: 1, error: (r.stderr || r.stdout).slice(0, 500) };
  const failed = stats.unexpected + stats.flaky;
  return { total: stats.expected + stats.unexpected + stats.flaky + stats.skipped, passed: stats.expected, failed, skipped: stats.skipped };
}
const e2e = playwright('local', { BASE_URL: '' });
suites.push(Object.assign({ name: 'Browser tests, local server (npm run test:e2e)', command: 'npm run test:e2e' }, e2e));
if (process.env.BASE_URL) {
  const dep = playwright('deployed', {});
  suites.push(Object.assign({ name: 'Browser + HTTP tests against ' + process.env.BASE_URL, command: 'BASE_URL=' + process.env.BASE_URL + ' npm run test:deployed' }, dep));
}

let browser = '';
const probe = spawnSync(process.execPath, ['-e', "require('@playwright/test').chromium.launch().then(async b=>{console.log(b.version());await b.close()})"], { cwd: ROOT, encoding: 'utf8' });
if (probe.status === 0 && probe.stdout.trim()) browser = 'Chromium ' + probe.stdout.trim();
const sha = run('git', ['rev-parse', '--short', 'HEAD']).stdout.trim();
const dirty = run('git', ['status', '--porcelain', '--', 'public', 'api', 'scripts', 'protocols', 'data', 'schema', 'test', 'server.js', 'verify.js']).stdout.trim() ? '+uncommitted' : '';

const NOT_COVERED = [
  'Clinical correctness of any protocol content (requires qualified clinical review).',
  'Behaviour on Meta Ray-Ban Display hardware, its browser, and Neural Band gesture-to-key mapping.',
  'Browsers other than Chromium (no Firefox or WebKit runs).',
  'Screen-reader output (semantics are set; no assistive-technology session was run).',
  'Real AI provider responses (provider behaviour is simulated with mocked responses).',
  'Service-worker update from one deployed version to the next.',
  'Field usability with health workers.'
];

const report = {
  recordedAt: new Date().toISOString().replace(/\.\d+Z$/, 'Z'),
  commit: sha + dirty,
  node: process.version,
  browser,
  coverage: coverage ? coverage.line : null,
  coverageDetail: coverage,
  suites,
  notCovered: NOT_COVERED
};
fs.writeFileSync(path.join(ROOT, 'public', 'test-results.json'), JSON.stringify(report, null, 2) + '\n');

const allPassed = suites.every(s => s.failed === 0);
const md = [
  '# Test results',
  '',
  'Generated by `npm run report` from runner output. Do not edit by hand.',
  '',
  '| | |', '|---|---|',
  '| Recorded | ' + report.recordedAt + ' |',
  '| Commit | `' + report.commit + '` |',
  '| Node | ' + report.node + ' |',
  '| Browser | ' + (browser || 'unknown') + ' |',
  '| Overall | ' + (allPassed ? '**All suites passed**' : '**FAILURES — see below**') + ' |',
  '',
  '| Suite | Command | Passed | Failed | Skipped | Total |', '|---|---|---|---|---|---|',
  ...suites.map(s => '| ' + s.name + ' | `' + s.command + '` | ' + s.passed + ' | ' + s.failed + ' | ' + (s.skipped || 0) + ' | ' + s.total + ' |'),
  ...(suites.some(s => s.skipped) ? ['', 'Skipped tests did not run and are not counted as passed. On a protected Vercel preview the offline (service-worker) tests skip, because Deployment Protection redirects the service-worker script request.'] : []),
  '',
  coverage ? 'Unit-test coverage of `public/js`, `api` and `scripts`: ' + coverage.line + '% lines, ' + coverage.branch + '% branches, ' + coverage.funcs + '% functions (Node built-in coverage). The browser-only files (`glasses-app.js`, page scripts) are exercised by the Playwright suite, which does not measure coverage.' : 'Coverage was not reported.',
  '',
  '## Not covered',
  '',
  ...NOT_COVERED.map(t => '- ' + t),
  '',
  'See [TESTING.md](TESTING.md) for what each suite proves.',
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'docs', 'TEST-RESULTS.md'), md);

for (const s of suites) console.log((s.failed ? '✗ ' : '✓ ') + s.name + ': ' + s.passed + '/' + s.total + (s.failed ? ' (' + s.failed + ' failed)' : '') + (s.skipped ? ' (' + s.skipped + ' skipped)' : '') + (s.error ? '\n  ' + s.error : ''));
if (coverage) console.log('coverage: ' + coverage.line + '% lines');
console.log('wrote docs/TEST-RESULTS.md and public/test-results.json');
process.exit(allPassed ? 0 : 1);
