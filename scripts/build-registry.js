#!/usr/bin/env node
// Generates public/generated/registry.js from protocols/*.json + data/roster.json,
// and stamps the service worker's precache list and build ID.
// Output is deterministic: the same inputs always produce byte-identical files,
// which is what lets `npm run verify` detect drift.
//
// Usage: node scripts/build-registry.js [--root <dir>]
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { loadAndValidate } = require('./lib/validate-protocol.js');

// Files the service worker precaches so the wearable workflow loads offline.
// Paths are URL paths relative to public/. '/' is served as glasses.html.
const APP_SHELL = [
  '/',
  '/glasses.html',
  '/js/engine.js',
  '/js/store.js',
  '/js/glasses-app.js',
  '/generated/registry.js',
  '/record.html',
  '/js/record-page.js',
  '/plan.html',
  '/js/planner.js',
  '/js/plan-page.js',
  '/review.html',
  '/js/review-page.js',
  '/css/phone.css',
  '/icon.png',
  '/icon-96.png'
];

const REGISTRY_REL = path.join('public', 'generated', 'registry.js');
const SW_REL = path.join('public', 'sw.js');
const SW_START = '// <generated: scripts/build-registry.js>';
const SW_END = '// </generated>';

const lf = s => s.replace(/\r\n/g, '\n');
const sha = s => crypto.createHash('sha256').update(s).digest('hex').slice(0, 12);

function renderRegistry(protocols, roster) {
  const payload = { protocols, roster };
  const data = {
    kind: 'dastak.registry',
    registryId: sha(JSON.stringify(payload)),
    protocols,
    roster
  };
  return [
    '/* GENERATED by scripts/build-registry.js from protocols/*.json and data/roster.json.',
    ' * DO NOT EDIT. Edit the canonical JSON and run `npm run build`; `npm run verify` fails on drift. */',
    '(function (root, data) {',
    "  if (typeof module === 'object' && module.exports) module.exports = data;",
    '  else root.DASTAK_REGISTRY = data;',
    "})(typeof self !== 'undefined' ? self : this, " + JSON.stringify(data, null, 2) + ');',
    ''
  ].join('\n');
}

function fileForUrl(rootDir, url) {
  return path.join(rootDir, 'public', url === '/' ? 'glasses.html' : url.slice(1));
}

// Returns { errors, outputs: { [relPath]: content } } without writing anything.
function build(rootDir) {
  const { errors, protocols, roster } = loadAndValidate(rootDir);
  if (errors.length) return { errors, outputs: {} };

  const registry = renderRegistry(protocols, roster);
  const hash = crypto.createHash('sha256');
  const missing = [];
  for (const url of APP_SHELL) {
    let content;
    if (url === '/generated/registry.js') content = registry;
    else {
      try { content = lf(fs.readFileSync(fileForUrl(rootDir, url), 'utf8')); }
      catch (e) { missing.push(url); continue; }
    }
    hash.update(url + '\0' + content + '\0');
  }
  if (missing.length) {
    return { errors: missing.map(u => ({ code: 'SHELL_FILE_MISSING', where: 'APP_SHELL', message: u + ' is listed for precaching but does not exist' })), outputs: {} };
  }
  const buildId = hash.digest('hex').slice(0, 12);

  let sw;
  try { sw = lf(fs.readFileSync(path.join(rootDir, SW_REL), 'utf8')); }
  catch (e) { return { errors: [{ code: 'FILE_PARSE', where: 'public/sw.js', message: e.message }], outputs: {} }; }
  const s = sw.indexOf(SW_START);
  const e = sw.indexOf(SW_END);
  if (s === -1 || e === -1 || e < s) {
    return { errors: [{ code: 'SW_MARKERS_MISSING', where: 'public/sw.js', message: 'Generated-section markers not found' }], outputs: {} };
  }
  const section = SW_START + '\n' +
    "var BUILD_ID = '" + buildId + "';\n" +
    'var APP_SHELL = ' + JSON.stringify(APP_SHELL, null, 2) + ';\n';
  const swOut = sw.slice(0, s) + section + sw.slice(e);

  return { errors: [], buildId, outputs: { [REGISTRY_REL]: registry, [SW_REL]: swOut } };
}

function printErrors(errors) {
  for (const e of errors) console.error('  ✗ [' + e.code + '] ' + e.where + ': ' + e.message);
}

if (require.main === module) {
  const i = process.argv.indexOf('--root');
  const rootDir = path.resolve(i !== -1 ? process.argv[i + 1] : path.join(__dirname, '..'));
  const result = build(rootDir);
  if (result.errors.length) {
    console.error('Build failed: ' + result.errors.length + ' error(s)');
    printErrors(result.errors);
    process.exit(1);
  }
  fs.mkdirSync(path.join(rootDir, 'public', 'generated'), { recursive: true });
  for (const [rel, content] of Object.entries(result.outputs)) {
    fs.writeFileSync(path.join(rootDir, rel), content);
    console.log('  wrote ' + rel.replace(/\\/g, '/'));
  }
  console.log('Build ' + result.buildId);
}

module.exports = { build, APP_SHELL, REGISTRY_REL, SW_REL, printErrors, lf };
